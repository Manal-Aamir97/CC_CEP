"""Check the curated Step 7 cases and score each one as the human wrote it.

    python -m dataset.check_cases     # checks dataset/cases/case_*.json, writes dataset/results/cases_summary.md

A case is a human-written resource from a fetched project, converted by hand into our schema. It
uses the same layout as a task file (so validator.validate() scores it unchanged) plus a
'provenance' block that ties it to the exact repository, commit, file and lines it came from.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

from dataset.baseline import RESULTS
from dataset.fetch_files import OUT as FETCHED
from validator import config_problems, validate
from validator.rules import RULES

CASES = Path(__file__).resolve().parent / "cases"
CASE_ID = re.compile(r"C\d{2}")
PREFIX = {"web_server": "WS", "storage_bucket": "ST", "database": "DB"}
KEYS = {"task_id", "set", "scored", "resource", "participant", "scoring", "initial_config", "provenance"}
PROVENANCE = {"repo", "commit", "commit_date", "path", "lines", "converted_by", "conversion_notes"}


def fetched_files():
    """{(repo, commit): set of paths} for every successfully fetched project."""
    path = FETCHED / "MANIFEST.json"
    if not path.exists():
        return None
    found = {}
    for entry in json.loads(path.read_text(encoding="utf-8")).values():
        if entry.get("status") == "ok":
            found[(entry["repo"], entry["commit"])] = {f["path"] for f in entry["files"] if "sha256" in f}
    return found


def case_problems(case, fetched):
    where = case.get("task_id", "?")
    missing = KEYS - case.keys()
    if missing:
        return [f"{where}: missing keys {sorted(missing)}"]
    problems = []
    if not CASE_ID.fullmatch(case["task_id"]):
        problems.append(f"{where}: task_id must look like C01")
    if case["set"] != "offline" or case["scored"] is not True:
        problems.append(f"{where}: set must be 'offline' and scored must be true")
    prefix = PREFIX.get(case["resource"])
    rules = case["scoring"].get("rules", [])
    if not rules:
        problems.append(f"{where}: no rules to score")
    for rid in rules:
        if rid not in RULES or rid[:2] != prefix:
            problems.append(f"{where}: rule {rid} does not apply to {case['resource']}")
    mapped = Counter(r for rids in case["scoring"].get("requirement_map", {}).values() for r in rids)
    if sorted(mapped.elements()) != sorted(rules):
        problems.append(f"{where}: requirement_map must list every scored rule exactly once")
    if case["initial_config"].get("resource") != case["resource"]:
        problems.append(f"{where}: initial_config is not a {case['resource']}")
    problems += [f"{where}: {p}" for p in config_problems(case["initial_config"])]

    provenance = case["provenance"]
    lacking = PROVENANCE - provenance.keys()
    if lacking:
        problems.append(f"{where}: provenance is missing {sorted(lacking)}")
    elif fetched is not None:
        paths = fetched.get((provenance["repo"], provenance["commit"]))
        if paths is None:
            problems.append(f"{where}: {provenance['repo']}@{provenance['commit'][:10]} was not fetched")
        elif provenance["path"] not in paths:
            problems.append(f"{where}: {provenance['path']} is not among the fetched files")
    return problems


def main():
    fetched = fetched_files()
    cases = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(CASES.glob("case_*.json"))]
    problems = [p for case in cases for p in case_problems(case, fetched)]
    if fetched is None:
        print("warning: no fetched-file manifest, so provenance was not cross-checked")
    if problems:
        print("Problems:\n  - " + "\n  - ".join(problems))
        return 1

    lines = ["# Step 7 cases: human-written configurations as written", "",
             "> Generated by `python -m dataset.check_cases`. Do not edit by hand.", "",
             "| Case | Resource | Source | Failed rules (validator) | Weighted score |", "|---|---|---|---|---|"]
    mix = Counter()
    for case in cases:
        result = validate(case["initial_config"], case)
        mix[(case["resource"], "failing" if result.error_count else "clean")] += 1
        source = f"{case['provenance']['repo']}@{case['provenance']['commit'][:10]}"
        lines.append(f"| {case['task_id']} | {case['resource']} | {source} | "
                     f"{', '.join(result.failed_rules) or 'none'} | {result.weighted_score} / {result.max_weighted_score} |")
    lines += ["", "Mix: " + ", ".join(f"{r} {s}: {n}" for (r, s), n in sorted(mix.items()))]
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "cases_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(cases)} case(s) valid; wrote {RESULTS / 'cases_summary.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
